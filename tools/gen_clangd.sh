#!/usr/bin/env bash
# Writes .clangd (gitignored) so clangd and the LSP tool read firmware/build/compile_commands.json cleanly (#196):
# GCC-only RISC-V flags are removed, and the toolchain's own system include dirs (picolibc) are added, read from
# the compiler itself so they follow toolchain updates. Run by build.sh after a P4 build; needs IDF's export.sh.
set -euo pipefail
repo=$(cd "$(dirname "$0")/.." && pwd)
gcc=$(command -v riscv32-esp-elf-gcc) || { echo "gen_clangd: riscv32-esp-elf-gcc not on PATH, .clangd not written" >&2; exit 0; }
mapfile -t dirs < <(echo | "$gcc" --specs=picolibc.specs -xc++ -E -v - 2>&1 |
    sed -n '/#include <...> search starts here/,/End of search list/p' | sed '1d;$d;s/^ *//' | xargs -r -n1 realpath -m)
{
    echo "# Generated by tools/gen_clangd.sh (#196); do not edit, rerun build.sh"
    echo "CompileFlags:"
    echo "  CompilationDatabase: firmware/build"
    echo "  Remove: [-march=*, -mabi=*, -mtune=*, -mno-*, -mcmodel=*, -specs=*, --specs=*, -fstrict-volatile-bitfields, -fno-tree-switch-conversion, -fzero-init-padding-bits=*, -fno-malloc-dce, -fno-shrink-wrap, -fanalyzer, -fdiagnostics-color=*]"
    printf '  Add: [--target=riscv32-unknown-elf, -march=rv32imafc_zicsr_zifencei, -mabi=ilp32f, -nostdinc, -nostdinc++, -Wno-unknown-warning-option'
    for d in "${dirs[@]}"; do printf ', -isystem, %s' "$d"; done
    echo "]"
} > "$repo/.clangd"
